import warnings
warnings.filterwarnings('ignore')

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
import torch

sns.set_style('whitegrid')
plt.rcParams['figure.figsize'] = (9, 5)
RANDOM_STATE = 42

print('PyTorch version:', torch.__version__)
print('CUDA available:', torch.cuda.is_available())

"""## 1. Load & Clean Data"""

# Point this at your CSV -- update the path if needed
DATA_PATH = '/content/diabetes_dataset_processed.csv'

df_raw = pd.read_csv(DATA_PATH)
print('Raw shape:', df_raw.shape)

LEAKY_COLS = ['HbA1c', 'Fasting_Glucose', 'Postprandial_Glucose', 'Source']
REDUNDANT_COLS = ['Gender', 'Family_History']
df = df_raw.drop(columns=LEAKY_COLS + REDUNDANT_COLS)

# Same feature engineering as the earlier notebooks
df['Pulse_Pressure'] = df['SBP'] - df['DBP']
df['WHR'] = df['Waist'] / df['Hip']
df['MAP'] = df['DBP'] + (df['SBP'] - df['DBP']) / 3
df['Chol_HDL_Ratio'] = df['Total_Cholesterol'] / df['HDL']

TARGET = 'Label'
FEATURES = [c for c in df.columns if c != TARGET]
binary_cols = ['Gender_Binary', 'Family_History_Binary']
numeric_cols = [c for c in FEATURES if c not in binary_cols]

print(f'{len(FEATURES)} features:', FEATURES)

from sklearn.impute import SimpleImputer

df[numeric_cols] = SimpleImputer(strategy='median').fit_transform(df[numeric_cols])
df[binary_cols] = SimpleImputer(strategy='most_frequent').fit_transform(df[binary_cols])
df[numeric_cols] = df[numeric_cols].replace([np.inf, -np.inf], np.nan)
df[numeric_cols] = df[numeric_cols].fillna(df[numeric_cols].median())

print('Remaining missing values:', df.isna().sum().sum())
df.to_csv('diabetes_processed_tabnet.csv', index=False)
print('Saved -> diabetes_processed_tabnet.csv')
df.head()

"""## 2. Train / Validation / Test Split, Scaling, SMOTE"""

from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from imblearn.over_sampling import SMOTE

X = df[FEATURES].values
y = df[TARGET].values

# First split off the test set, then split train into train/validation
# (TabNet uses a validation set internally for early stopping)
X_train_full, X_test, y_train_full, y_test = train_test_split(
    X, y, test_size=0.2, random_state=RANDOM_STATE, stratify=y
)
X_train, X_valid, y_train, y_valid = train_test_split(
    X_train_full, y_train_full, test_size=0.15, random_state=RANDOM_STATE, stratify=y_train_full
)

scaler = StandardScaler()
X_train_scaled = scaler.fit_transform(X_train)
X_valid_scaled = scaler.transform(X_valid)
X_test_scaled = scaler.transform(X_test)

# Balance the training set only (SMOTE)
X_train_sm, y_train_sm = SMOTE(random_state=RANDOM_STATE).fit_resample(X_train_scaled, y_train)

print('Train (balanced):', X_train_sm.shape)
print('Validation        :', X_valid_scaled.shape)
print('Test              :', X_test_scaled.shape)

"""## 3. Define & Train TabNet

Key hyperparameters:
- `n_d` / `n_a`: width of the decision/attention layers (feature representation size)
- `n_steps`: number of sequential attention steps (how many times the model re-examines features)
- `gamma`: relaxation parameter controlling how much a feature can be reused across steps
- `lambda_sparse`: sparsity regularization -- encourages the model to focus on fewer features per step

"""

from pytorch_tabnet.tab_model import TabNetClassifier

tabnet = TabNetClassifier(
    n_d=16,
    n_a=16,
    n_steps=5,
    gamma=1.5,
    lambda_sparse=1e-3,
    optimizer_fn=torch.optim.Adam,
    optimizer_params=dict(lr=2e-2),
    scheduler_fn=torch.optim.lr_scheduler.StepLR,
    scheduler_params=dict(step_size=20, gamma=0.9),
    mask_type='sparsemax',
    seed=RANDOM_STATE,
    verbose=1,
)

tabnet.fit(
    X_train=X_train_sm, y_train=y_train_sm,
    eval_set=[(X_train_sm, y_train_sm), (X_valid_scaled, y_valid)],
    eval_name=['train', 'valid'],
    eval_metric=['auc', 'accuracy'],
    max_epochs=200,
    patience=30,
    batch_size=64,
    virtual_batch_size=32,
    num_workers=0,
    drop_last=False,
)

"""## 4. Plot Training History"""

history = tabnet.history

fig, axes = plt.subplots(1, 2, figsize=(14, 5))

axes[0].plot(history['loss'], label='Training Loss')
axes[0].set_xlabel('Epoch'); axes[0].set_ylabel('Loss')
axes[0].set_title('TabNet Training Loss')
axes[0].legend()

axes[1].plot(history['valid_auc'], label='Validation AUC', color='#2E7D32')
axes[1].set_xlabel('Epoch'); axes[1].set_ylabel('ROC-AUC')
axes[1].set_title('TabNet Validation ROC-AUC')
axes[1].legend()

plt.tight_layout()
plt.savefig('fig_tabnet_training_history.png', dpi=120)
plt.show()

"""## 5. Evaluate on the Test Set"""

from sklearn.metrics import (roc_auc_score, accuracy_score, precision_score, recall_score,
                              f1_score, roc_curve, confusion_matrix, classification_report)

proba_tabnet = tabnet.predict_proba(X_test_scaled)[:, 1]
auc_tabnet = roc_auc_score(y_test, proba_tabnet)
print(f'TabNet Test ROC-AUC: {auc_tabnet:.4f}')

def best_threshold_accuracy(proba, y_true):
    best_acc, best_t = 0, 0.5
    for t in np.arange(0.20, 0.81, 0.01):
        acc = accuracy_score(y_true, (proba >= t).astype(int))
        if acc > best_acc:
            best_acc, best_t = acc, t
    return best_acc, best_t

acc_tabnet, t_tabnet = best_threshold_accuracy(proba_tabnet, y_test)
pred_tabnet = (proba_tabnet >= t_tabnet).astype(int)

print(f'Best threshold : {t_tabnet:.2f}')
print(f'Accuracy       : {acc_tabnet:.4f}')
print(f'Precision      : {precision_score(y_test, pred_tabnet):.4f}')
print(f'Recall         : {recall_score(y_test, pred_tabnet):.4f}')
print(f'F1             : {f1_score(y_test, pred_tabnet):.4f}')
print()
print(classification_report(y_test, pred_tabnet, target_names=['No Diabetes', 'Diabetes']))

"""## 6. ROC Curve"""

fpr, tpr, _ = roc_curve(y_test, proba_tabnet)

plt.figure(figsize=(8, 7))
plt.plot(fpr, tpr, color='#7B2CBF', linewidth=2.5, label=f'TabNet (AUC={auc_tabnet:.3f})')
plt.plot([0, 1], [0, 1], 'k--', alpha=0.5)
plt.xlabel('False Positive Rate')
plt.ylabel('True Positive Rate')
plt.title('ROC Curve — TabNet')
plt.legend(loc='lower right')
plt.tight_layout()
plt.savefig('fig_tabnet_roc_curve.png', dpi=120)
plt.show()

"""## 7. Confusion Matrix"""

cm = confusion_matrix(y_test, pred_tabnet)

plt.figure(figsize=(6, 5))
sns.heatmap(cm, annot=True, fmt='d', cmap='Purples',
            xticklabels=['No Diabetes', 'Diabetes'], yticklabels=['No Diabetes', 'Diabetes'])
plt.xlabel('Predicted'); plt.ylabel('Actual')
plt.title(f'Confusion Matrix — TabNet (threshold={t_tabnet:.2f})')
plt.tight_layout()
plt.savefig('fig_tabnet_confusion_matrix.png', dpi=120)
plt.show()

"""## 8. TabNet's Built-In Feature Importance

Unlike black-box neural networks, TabNet produces its own feature importance scores
directly from its attention masks -- no separate SHAP/LIME step is strictly required
for a global importance ranking (though SHAP can still be used for per-sample
explanations, see the optional section below).

"""

importances = pd.Series(tabnet.feature_importances_, index=FEATURES).sort_values(ascending=False)

plt.figure(figsize=(9, 6))
sns.barplot(x=importances.values, y=importances.index, color='#7B2CBF')
plt.title('TabNet Feature Importance (built-in attention-based)')
plt.xlabel('Importance')
plt.tight_layout()
plt.savefig('fig_tabnet_feature_importance.png', dpi=120)
plt.show()

