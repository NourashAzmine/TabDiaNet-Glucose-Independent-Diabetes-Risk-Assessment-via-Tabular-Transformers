"""## 10. Model Comparison Charts"""

plt.figure(figsize=(10, 8))
plot_df = results_df.sort_values('Test ROC-AUC')
colors = ['#C44E52' if 'Neural' in m else '#4C72B0' for m in plot_df['Model']]
plt.barh(plot_df['Model'], plot_df['Test ROC-AUC'], color=colors)
