"""## 12. SHAP Analysis

We run SHAP (SHapley Additive exPlanations) on the best-performing **tree-based**
individual model to interpret feature contributions. SHAP's `TreeExplainer` is fast
and exact for tree ensembles (Random Forest / XGBoost / Gradient Boosting), so we pick
the best tree-based model rather than the neural net or SVM (which need slower,
approximate, or kernel-based explainers).

"""

import shap

tree_models = ['Random Forest', 'Extra Trees', 'Gradient Boosting', 'XGBoost', 'Decision Tree']
tree_results = results_df[results_df['Model'].isin(tree_models)].sort_values('Test ROC-AUC', ascending=False)
shap_target_name = tree_results.iloc[0]['Model']
shap_model = fitted_models[shap_target_name]
print(f'Running SHAP on: {shap_target_name}')

X_test_df = pd.DataFrame(X_test_scaled, columns=FEATURES)

explainer = shap.TreeExplainer(shap_model)
shap_values = explainer.shap_values(X_test_df)

# shap_values may be a list (per-class), or a 3D array (samples, features, classes)
# depending on the model type/SHAP version -- normalize to a 2D (samples, features) array
# for the positive (diabetes) class.
if isinstance(shap_values, list):
    shap_values_plot = shap_values[1]
elif isinstance(shap_values, np.ndarray) and shap_values.ndim == 3:
    shap_values_plot = shap_values[:, :, 1]
else:
    shap_values_plot = shap_values

print('SHAP values shape:', np.array(shap_values_plot).shape)

plt.figure()
shap.summary_plot(shap_values_plot, X_test_df, show=False)
plt.title(f'SHAP Summary Plot — {shap_target_name}')
plt.tight_layout()
plt.savefig('fig_shap_summary.png', dpi=120, bbox_inches='tight')
plt.show()

plt.figure()
shap.summary_plot(shap_values_plot, X_test_df, plot_type='bar', show=False)
plt.title(f'SHAP Feature Importance — {shap_target_name}')
plt.tight_layout()
plt.savefig('fig_shap_bar_importance.png', dpi=120, bbox_inches='tight')
plt.show()

# Dependence plots for the top 3 most important features
mean_abs_shap = np.abs(shap_values_plot).mean(axis=0)
top_features = pd.Series(mean_abs_shap, index=FEATURES).sort_values(ascending=False).head(3).index.tolist()
print('Top 3 features by mean |SHAP value|:', top_features)

for feat in top_features:
    plt.figure()
    shap.dependence_plot(feat, shap_values_plot, X_test_df, show=False)
    plt.title(f'SHAP Dependence Plot — {feat}')
    plt.tight_layout()
    plt.savefig(f'fig_shap_dependence_{feat}.png', dpi=120, bbox_inches='tight')
    plt.show()

# A single-patient explanation (force/waterfall plot) for one correctly predicted diabetic case
diabetic_idx = np.where((y_test.values == 1) & (shap_model.predict(X_test_scaled) == 1))[0][0]

exp = shap.Explanation(values=shap_values_plot[diabetic_idx], base_values=explainer.expected_value
                        if not isinstance(explainer.expected_value, (list, np.ndarray)) else explainer.expected_value[1],
                        data=X_test_df.iloc[diabetic_idx], feature_names=FEATURES)

plt.figure()
shap.waterfall_plot(exp, show=False)
plt.title(f'SHAP Waterfall — Example Diabetic Patient (index {diabetic_idx})')
plt.tight_layout()
plt.savefig('fig_shap_waterfall_example.png', dpi=120, bbox_inches='tight')
plt.show()

