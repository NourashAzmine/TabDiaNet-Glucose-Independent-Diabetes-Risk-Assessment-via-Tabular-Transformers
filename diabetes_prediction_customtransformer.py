"""## 7. Bag 10 Transformers Together

Each copy is trained on a **bootstrap resample** of the (already SMOTE-balanced)
training set with a different random seed, so the 10 models make correlated-but-not-
identical errors. Averaging their predicted probabilities reduces variance -- the
same principle that took your custom MLP from ~77% (single) to ~79.7% (bagged).

"""

N_BAGS = 10
rng = np.random.RandomState(RANDOM_STATE)

bagged_models = []
n_train = len(y_train_sm)

for i in range(N_BAGS):
    boot_idx = rng.choice(n_train, size=n_train, replace=True)
    X_cont_boot = X_train_cont_sm[boot_idx]
    X_cat_boot = X_train_cat_sm[boot_idx]
    y_boot = y_train_sm[boot_idx]

    model_i, auc_i, _ = train_one_transformer(
        seed=RANDOM_STATE + i, X_cont_tr=X_cont_boot, X_cat_tr=X_cat_boot, y_tr=y_boot, verbose=False
    )
    bagged_models.append(model_i)
    print(f'Model {i+1}/{N_BAGS} trained -- validation AUC: {auc_i:.4f}')

print(f'\n{len(bagged_models)} models bagged.')

"""## 8. Evaluate the Bagged Custom Transformer on the Test Set"""

from sklearn.metrics import (accuracy_score, precision_score, recall_score, f1_score,
                              roc_curve, confusion_matrix, classification_report)

test_loader = DataLoader(test_ds, batch_size=BATCH_SIZE, shuffle=False)

def predict_proba(model, loader):
    model.eval()
    probs = []
    with torch.no_grad():
        for x_cont, x_cat, _ in loader:
            x_cont, x_cat = x_cont.to(device), x_cat.to(device)
            logits = model(x_cont, x_cat)
            probs.append(torch.sigmoid(logits).cpu().numpy())
    return np.concatenate(probs)

all_probs = np.array([predict_proba(m, test_loader) for m in bagged_models])   # (N_BAGS, n_test)
proba_bagged = all_probs.mean(axis=0)

auc_bagged = roc_auc_score(y_test, proba_bagged)
print(f'Bagged Custom Transformer -- Test ROC-AUC: {auc_bagged:.4f}')

def best_threshold_accuracy(proba, y_true):
    best_acc, best_t = 0, 0.5
    for t in np.arange(0.20, 0.81, 0.01):
        acc = accuracy_score(y_true, (proba >= t).astype(int))
        if acc > best_acc:
            best_acc, best_t = acc, t
    return best_acc, best_t

