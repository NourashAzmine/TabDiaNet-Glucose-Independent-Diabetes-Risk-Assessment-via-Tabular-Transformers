"""## 4. Custom Lightweight Transformer Architecture

Built from scratch (not a library wrapper) so every regularization choice is explicit
and tunable:

- **Feature Tokenizer**: each continuous feature gets its own learned linear
  projection into a `d_token`-dim vector; each categorical feature gets an embedding
  lookup. A learnable `[CLS]` token is prepended, exactly as in FT-Transformer.
- **Feature Dropout**: during training, entire feature tokens are randomly zeroed out
  (not just individual activations) -- this is the tabular equivalent of dropping
  whole words in NLP, forcing the attention mechanism to not over-rely on any one
  clinical measurement.
- **Small `nn.TransformerEncoder`**: 2 layers, 4 heads, `d_token=16` -- roughly 10x
  fewer parameters than the earlier FT-Transformer run.
- **Label smoothing** is applied in the loss function (Section 6), not the model
  itself.

"""

class FeatureTokenizer(nn.Module):
    def __init__(self, n_continuous, cat_cardinalities, d_token):
        super().__init__()
        self.n_continuous = n_continuous
        self.d_token = d_token

        # One learned (weight, bias) pair per continuous feature: scalar -> d_token vector
        self.cont_weight = nn.Parameter(torch.randn(n_continuous, d_token) * 0.02)
        self.cont_bias = nn.Parameter(torch.zeros(n_continuous, d_token))

        # One embedding table per categorical feature
        self.cat_embeddings = nn.ModuleList([
            nn.Embedding(cardinality, d_token) for cardinality in cat_cardinalities
        ])

        self.cls_token = nn.Parameter(torch.randn(1, 1, d_token) * 0.02)

    def forward(self, x_cont, x_cat):
        batch_size = x_cont.shape[0]

        # (batch, n_continuous, d_token)
        cont_tokens = x_cont.unsqueeze(-1) * self.cont_weight.unsqueeze(0) + self.cont_bias.unsqueeze(0)

        cat_tokens = []
        for i, emb in enumerate(self.cat_embeddings):
            cat_tokens.append(emb(x_cat[:, i]).unsqueeze(1))
        cat_tokens = torch.cat(cat_tokens, dim=1) if cat_tokens else torch.empty(batch_size, 0, self.d_token, device=x_cont.device)

        cls = self.cls_token.expand(batch_size, -1, -1)
        tokens = torch.cat([cls, cont_tokens, cat_tokens], dim=1)   # (batch, 1 + n_features, d_token)
        return tokens


class FeatureDropout(nn.Module):
    """Randomly zeroes out entire feature tokens (never the CLS token) during training."""
    def __init__(self, p=0.15):
        super().__init__()
        self.p = p

    def forward(self, tokens):
        if not self.training or self.p == 0:
            return tokens
        batch_size, n_tokens, d_token = tokens.shape
        mask = torch.ones(batch_size, n_tokens, 1, device=tokens.device)
        feature_mask = (torch.rand(batch_size, n_tokens - 1, 1, device=tokens.device) > self.p).float()
        mask[:, 1:, :] = feature_mask
        return tokens * mask


class CustomTabularTransformer(nn.Module):
    def __init__(self, n_continuous, cat_cardinalities, d_token=16, n_heads=4,
                 n_layers=2, ff_mult=2, dropout=0.3, feature_dropout_p=0.15):
        super().__init__()
        self.tokenizer = FeatureTokenizer(n_continuous, cat_cardinalities, d_token)
        self.feature_dropout = FeatureDropout(feature_dropout_p)

        encoder_layer = nn.TransformerEncoderLayer(
            d_model=d_token, nhead=n_heads, dim_feedforward=d_token * ff_mult,
            dropout=dropout, activation='gelu', batch_first=True, norm_first=True,
        )
        self.encoder = nn.TransformerEncoder(encoder_layer, num_layers=n_layers)

        self.norm = nn.LayerNorm(d_token)
        self.head = nn.Sequential(
            nn.Dropout(dropout),
            nn.Linear(d_token, d_token // 2),
            nn.GELU(),
            nn.Dropout(dropout),
            nn.Linear(d_token // 2, 1),
        )

    def forward(self, x_cont, x_cat):
        tokens = self.tokenizer(x_cont, x_cat)
        tokens = self.feature_dropout(tokens)
        encoded = self.encoder(tokens)
        cls_output = self.norm(encoded[:, 0, :])   # take the CLS token's representation
        return self.head(cls_output).squeeze(-1)


def count_params(model):
    return sum(p.numel() for p in model.parameters())

