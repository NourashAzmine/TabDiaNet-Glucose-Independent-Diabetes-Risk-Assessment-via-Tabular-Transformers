"""## 5. Label-Smoothed BCE Loss

Standard binary cross-entropy pushes predictions toward exactly 0 or 1. On a small,
somewhat noisy dataset, this encourages overconfidence and overfitting. Label
smoothing softens the targets slightly (e.g., 1 -> 0.95, 0 -> 0.05).

"""

class LabelSmoothingBCELoss(nn.Module):
    def __init__(self, smoothing=0.05):
        super().__init__()
        self.smoothing = smoothing

    def forward(self, logits, targets):
        smoothed = targets * (1 - self.smoothing) + 0.5 * self.smoothing
        return F.binary_cross_entropy_with_logits(logits, smoothed)

"""## 6. Train One Transformer (Single Run First, to Verify Overfitting Is Fixed)"""

from sklearn.metrics import roc_auc_score

def train_one_transformer(seed, X_cont_tr, X_cat_tr, y_tr, max_epochs=150, patience=20, verbose=False):
    torch.manual_seed(seed)
    np.random.seed(seed)

    train_ds_i = DiabetesTabularDataset(X_cont_tr, X_cat_tr, y_tr)
    train_loader_i = DataLoader(train_ds_i, batch_size=BATCH_SIZE, shuffle=True)
    valid_loader = DataLoader(valid_ds, batch_size=BATCH_SIZE, shuffle=False)

    model = CustomTabularTransformer(
        n_continuous=n_cont, cat_cardinalities=[2, 2],
        d_token=16, n_heads=4, n_layers=2, ff_mult=2,
        dropout=0.3, feature_dropout_p=0.15,
    ).to(device)

    criterion = LabelSmoothingBCELoss(smoothing=0.05)
    optimizer = torch.optim.AdamW(model.parameters(), lr=3e-4, weight_decay=1e-2)
    scheduler = torch.optim.lr_scheduler.CosineAnnealingWarmRestarts(optimizer, T_0=20, T_mult=1)

    best_valid_auc = 0.0
    epochs_no_improve = 0
    best_state = None
    history = {'train_loss': [], 'valid_auc': []}

    for epoch in range(max_epochs):
        model.train()
        epoch_loss = 0.0
        for x_cont, x_cat, yb in train_loader_i:
            x_cont, x_cat, yb = x_cont.to(device), x_cat.to(device), yb.to(device)
            optimizer.zero_grad()
            logits = model(x_cont, x_cat)
            loss = criterion(logits, yb)
            loss.backward()
            torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=1.0)
            optimizer.step()
            epoch_loss += loss.item() * len(yb)
        scheduler.step()
        epoch_loss /= len(train_ds_i)

        model.eval()
        val_probs, val_true = [], []
        with torch.no_grad():
            for x_cont, x_cat, yb in valid_loader:
                x_cont, x_cat = x_cont.to(device), x_cat.to(device)
                logits = model(x_cont, x_cat)
                val_probs.append(torch.sigmoid(logits).cpu().numpy())
                val_true.append(yb.numpy())
        val_probs = np.concatenate(val_probs)
        val_true = np.concatenate(val_true)
        val_auc = roc_auc_score(val_true, val_probs)

        history['train_loss'].append(epoch_loss)
        history['valid_auc'].append(val_auc)

        if val_auc > best_valid_auc:
            best_valid_auc = val_auc
            best_state = {k: v.clone() for k, v in model.state_dict().items()}
            epochs_no_improve = 0
        else:
            epochs_no_improve += 1

        if verbose and (epoch % 10 == 0 or epoch == max_epochs - 1):
            print(f'  Epoch {epoch:3d} | Loss: {epoch_loss:.4f} | Valid AUC: {val_auc:.4f} | Best: {best_valid_auc:.4f}')

        if epochs_no_improve >= patience:
            if verbose:
                print(f'  Early stopping at epoch {epoch}')
            break

    model.load_state_dict(best_state)
    return model, best_valid_auc, history


