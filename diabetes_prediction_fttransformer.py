import warnings
warnings.filterwarnings('ignore')

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
import torch
import torch.nn as nn
from torch.utils.data import Dataset, DataLoader

sns.set_style('whitegrid')
plt.rcParams['figure.figsize'] = (9, 5)
RANDOM_STATE = 42
torch.manual_seed(RANDOM_STATE)
np.random.seed(RANDOM_STATE)

device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
print('PyTorch version:', torch.__version__)
print('Device:', device)

"""## 1. Load & Clean Data"""

# Point this at your CSV -- update the path if needed
DATA_PATH = '/content/diabetes_dataset_processed.csv'

df_raw = pd.read_csv(DATA_PATH)
print('Raw shape:', df_raw.shape)

LEAKY_COLS = ['HbA1c', 'Fasting_Glucose', 'Postprandial_Glucose', 'Source']
REDUNDANT_COLS = ['Gender', 'Family_History']
df = df_raw.drop(columns=LEAKY_COLS + REDUNDANT_COLS)

# Same feature engineering as the earlier notebooks
df['Pulse_Pressure'] = df['SBP'] - df['DBP']
df['WHR'] = df['Waist'] / df['Hip']
df['MAP'] = df['DBP'] + (df['SBP'] - df['DBP']) / 3
df['Chol_HDL_Ratio'] = df['Total_Cholesterol'] / df['HDL']

TARGET = 'Label'
CATEGORICAL_COLS = ['Gender_Binary', 'Family_History_Binary']   # true binary/categorical features
CONTINUOUS_COLS = [c for c in df.columns if c not in CATEGORICAL_COLS + [TARGET]]

print(f'{len(CATEGORICAL_COLS)} categorical + {len(CONTINUOUS_COLS)} continuous features')
print('Categorical:', CATEGORICAL_COLS)
print('Continuous :', CONTINUOUS_COLS)

from sklearn.impute import SimpleImputer

df[CONTINUOUS_COLS] = SimpleImputer(strategy='median').fit_transform(df[CONTINUOUS_COLS])
df[CATEGORICAL_COLS] = SimpleImputer(strategy='most_frequent').fit_transform(df[CATEGORICAL_COLS])
df[CONTINUOUS_COLS] = df[CONTINUOUS_COLS].replace([np.inf, -np.inf], np.nan)
df[CONTINUOUS_COLS] = df[CONTINUOUS_COLS].fillna(df[CONTINUOUS_COLS].median())

# Categorical columns must be non-negative integer category indices for FT-Transformer
for c in CATEGORICAL_COLS:
    df[c] = df[c].astype(int)

print('Remaining missing values:', df.isna().sum().sum())
df.to_csv('diabetes_processed_fttransformer.csv', index=False)
print('Saved -> diabetes_processed_fttransformer.csv')
df.head()

"""## 2. Train / Validation / Test Split, Scaling, SMOTE"""

from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from imblearn.over_sampling import SMOTE

FEATURES = CONTINUOUS_COLS + CATEGORICAL_COLS   # order matters -- kept consistent throughout
X = df[FEATURES].values
y = df[TARGET].values

X_train_full, X_test, y_train_full, y_test = train_test_split(
    X, y, test_size=0.2, random_state=RANDOM_STATE, stratify=y
)
X_train, X_valid, y_train, y_valid = train_test_split(
    X_train_full, y_train_full, test_size=0.15, random_state=RANDOM_STATE, stratify=y_train_full
)

n_cont = len(CONTINUOUS_COLS)

# Scale ONLY the continuous columns; leave categorical integer codes untouched
scaler = StandardScaler()
X_train_cont = scaler.fit_transform(X_train[:, :n_cont])
X_valid_cont = scaler.transform(X_valid[:, :n_cont])
X_test_cont  = scaler.transform(X_test[:, :n_cont])

X_train_cat = X_train[:, n_cont:]
X_valid_cat = X_valid[:, n_cont:]
X_test_cat  = X_test[:, n_cont:]

# SMOTE on the continuous+categorical block together (training set only), then split back apart
X_train_full_scaled = np.hstack([X_train_cont, X_train_cat])
X_train_sm, y_train_sm = SMOTE(random_state=RANDOM_STATE).fit_resample(X_train_full_scaled, y_train)

X_train_cont_sm = X_train_sm[:, :n_cont]
X_train_cat_sm  = np.round(X_train_sm[:, n_cont:]).astype(int)   # SMOTE can produce non-integer categoricals -- round them back
X_train_cat_sm  = np.clip(X_train_cat_sm, 0, 1)                  # keep valid for our 2 binary categorical features

print('Train (balanced):', X_train_cont_sm.shape[0])
print('Validation      :', X_valid_cont.shape[0])
print('Test            :', X_test_cont.shape[0])

"""## 3. PyTorch Dataset & DataLoader"""

class DiabetesTabularDataset(Dataset):
    def __init__(self, X_cont, X_cat, y):
        self.X_cont = torch.tensor(X_cont, dtype=torch.float32)
        self.X_cat = torch.tensor(X_cat, dtype=torch.long)
        self.y = torch.tensor(y, dtype=torch.float32)

    def __len__(self):
        return len(self.y)

    def __getitem__(self, idx):
        return self.X_cat[idx], self.X_cont[idx], self.y[idx]


train_ds = DiabetesTabularDataset(X_train_cont_sm, X_train_cat_sm, y_train_sm)
valid_ds = DiabetesTabularDataset(X_valid_cont, X_valid_cat, y_valid)
test_ds  = DiabetesTabularDataset(X_test_cont, X_test_cat, y_test)

BATCH_SIZE = 64
train_loader = DataLoader(train_ds, batch_size=BATCH_SIZE, shuffle=True)
valid_loader = DataLoader(valid_ds, batch_size=BATCH_SIZE, shuffle=False)
test_loader  = DataLoader(test_ds, batch_size=BATCH_SIZE, shuffle=False)

print(f'Batches -- train: {len(train_loader)}, valid: {len(valid_loader)}, test: {len(test_loader)}')

"""## 4. Define the FT-Transformer

Key hyperparameters:
- `dim`: token embedding dimension (paper default: 32)
- `depth`: number of Transformer encoder blocks (paper default: 6)
- `heads`: number of self-attention heads (paper default: 8)
- `categories`: number of unique values per categorical column (both our binary flags have 2)

"""

from tab_transformer_pytorch import FTTransformer

model = FTTransformer(
    categories=tuple([2] * len(CATEGORICAL_COLS)),   # (2, 2) for Gender_Binary, Family_History_Binary
    num_continuous=n_cont,
    dim=32,
    dim_out=1,          # single logit for binary classification
    depth=6,
    heads=8,
    attn_dropout=0.1,
    ff_dropout=0.1,
).to(device)

n_params = sum(p.numel() for p in model.parameters())
print(f'FT-Transformer parameters: {n_params:,}')

"""## 5. Training Loop"""

from sklearn.metrics import roc_auc_score

criterion = nn.BCEWithLogitsLoss()
optimizer = torch.optim.AdamW(model.parameters(), lr=1e-4, weight_decay=1e-5)
scheduler = torch.optim.lr_scheduler.ReduceLROnPlateau(optimizer, mode='max', factor=0.5, patience=8)

MAX_EPOCHS = 150
PATIENCE = 25

best_valid_auc = 0.0
epochs_no_improve = 0
best_state = None

history = {'train_loss': [], 'valid_auc': []}

for epoch in range(MAX_EPOCHS):
    model.train()
    epoch_loss = 0.0
    for x_cat, x_cont, yb in train_loader:
        x_cat, x_cont, yb = x_cat.to(device), x_cont.to(device), yb.to(device)
        optimizer.zero_grad()
        logits = model(x_cat, x_cont).squeeze(-1)
        loss = criterion(logits, yb)
        loss.backward()
        optimizer.step()
        epoch_loss += loss.item() * len(yb)
    epoch_loss /= len(train_ds)

    # Validation
    model.eval()
    val_probs, val_true = [], []
    with torch.no_grad():
        for x_cat, x_cont, yb in valid_loader:
            x_cat, x_cont = x_cat.to(device), x_cont.to(device)
            logits = model(x_cat, x_cont).squeeze(-1)
            val_probs.append(torch.sigmoid(logits).cpu().numpy())
            val_true.append(yb.numpy())
    val_probs = np.concatenate(val_probs)
    val_true = np.concatenate(val_true)
    val_auc = roc_auc_score(val_true, val_probs)

    history['train_loss'].append(epoch_loss)
    history['valid_auc'].append(val_auc)
    scheduler.step(val_auc)

    if val_auc > best_valid_auc:
        best_valid_auc = val_auc
        best_state = {k: v.clone() for k, v in model.state_dict().items()}
        epochs_no_improve = 0
    else:
        epochs_no_improve += 1

    if epoch % 5 == 0 or epoch == MAX_EPOCHS - 1:
        print(f'Epoch {epoch:3d} | Train Loss: {epoch_loss:.4f} | Valid AUC: {val_auc:.4f} | Best: {best_valid_auc:.4f}')

    if epochs_no_improve >= PATIENCE:
        print(f'Early stopping at epoch {epoch} (no improvement for {PATIENCE} epochs)')
        break

model.load_state_dict(best_state)
print(f'\nBest validation ROC-AUC: {best_valid_auc:.4f}')

"""## 6. Plot Training History"""

fig, axes = plt.subplots(1, 2, figsize=(14, 5))

axes[0].plot(history['train_loss'], color='#7B2CBF')
axes[0].set_xlabel('Epoch'); axes[0].set_ylabel('Loss')
axes[0].set_title('FT-Transformer Training Loss')

axes[1].plot(history['valid_auc'], color='#2E7D32')
axes[1].set_xlabel('Epoch'); axes[1].set_ylabel('ROC-AUC')
axes[1].set_title('FT-Transformer Validation ROC-AUC')

plt.tight_layout()
plt.savefig('fig_fttransformer_training_history.png', dpi=120)
plt.show()

"""## 7. Evaluate on the Test Set"""

from sklearn.metrics import (roc_auc_score, accuracy_score, precision_score, recall_score,
                              f1_score, roc_curve, confusion_matrix, classification_report)

model.eval()
test_probs, test_true = [], []
with torch.no_grad():
    for x_cat, x_cont, yb in test_loader:
        x_cat, x_cont = x_cat.to(device), x_cont.to(device)
        logits = model(x_cat, x_cont).squeeze(-1)
        test_probs.append(torch.sigmoid(logits).cpu().numpy())
        test_true.append(yb.numpy())

proba_ft = np.concatenate(test_probs)
y_test_arr = np.concatenate(test_true)

auc_ft = roc_auc_score(y_test_arr, proba_ft)
print(f'FT-Transformer Test ROC-AUC: {auc_ft:.4f}')

def best_threshold_accuracy(proba, y_true):
    best_acc, best_t = 0, 0.5
    for t in np.arange(0.20, 0.81, 0.01):
        acc = accuracy_score(y_true, (proba >= t).astype(int))
        if acc > best_acc:
            best_acc, best_t = acc, t
    return best_acc, best_t

acc_ft, t_ft = best_threshold_accuracy(proba_ft, y_test_arr)
pred_ft = (proba_ft >= t_ft).astype(int)

print(f'Best threshold : {t_ft:.2f}')
print(f'Accuracy       : {acc_ft:.4f}')
print(f'Precision      : {precision_score(y_test_arr, pred_ft):.4f}')
print(f'Recall         : {recall_score(y_test_arr, pred_ft):.4f}')
print(f'F1             : {f1_score(y_test_arr, pred_ft):.4f}')
print()
print(classification_report(y_test_arr, pred_ft, target_names=['No Diabetes', 'Diabetes']))

"""## 8. ROC Curve"""

fpr, tpr, _ = roc_curve(y_test_arr, proba_ft)

plt.figure(figsize=(8, 7))
plt.plot(fpr, tpr, color='#C44E52', linewidth=2.5, label=f'FT-Transformer (AUC={auc_ft:.3f})')
plt.plot([0, 1], [0, 1], 'k--', alpha=0.5)
plt.xlabel('False Positive Rate')
plt.ylabel('True Positive Rate')
plt.title('ROC Curve — FT-Transformer')
plt.legend(loc='lower right')
plt.tight_layout()
