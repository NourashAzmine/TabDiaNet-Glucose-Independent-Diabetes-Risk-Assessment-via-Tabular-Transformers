"""## 10. Feature Importance (Permutation-Based)

FT-Transformer doesn't expose a single built-in importance score the way TabNet does,
so we use **permutation importance**: shuffle one feature at a time in the test set
and measure how much the ROC-AUC drops. A larger drop means the model relies on that
feature more heavily.

"""

def get_test_auc(x_cont_arr, x_cat_arr, y_arr):
    ds = DiabetesTabularDataset(x_cont_arr, x_cat_arr, y_arr)
    loader = DataLoader(ds, batch_size=BATCH_SIZE, shuffle=False)
    probs = []
    model.eval()
    with torch.no_grad():
        for x_cat, x_cont, _ in loader:
            x_cat, x_cont = x_cat.to(device), x_cont.to(device)
            logits = model(x_cat, x_cont).squeeze(-1)
            probs.append(torch.sigmoid(logits).cpu().numpy())
    probs = np.concatenate(probs)
    return roc_auc_score(y_arr, probs)

baseline_auc = get_test_auc(X_test_cont, X_test_cat, y_test_arr)
importances = {}

rng = np.random.RandomState(RANDOM_STATE)

for i, feat in enumerate(CONTINUOUS_COLS):
    X_test_cont_perm = X_test_cont.copy()
    rng.shuffle(X_test_cont_perm[:, i])
    perm_auc = get_test_auc(X_test_cont_perm, X_test_cat, y_test_arr)
    importances[feat] = baseline_auc - perm_auc

for i, feat in enumerate(CATEGORICAL_COLS):
    X_test_cat_perm = X_test_cat.copy()
    rng.shuffle(X_test_cat_perm[:, i])
    perm_auc = get_test_auc(X_test_cont, X_test_cat_perm, y_test_arr)
    importances[feat] = baseline_auc - perm_auc

importances = pd.Series(importances).sort_values(ascending=False)
print(f'Baseline Test ROC-AUC: {baseline_auc:.4f}')
importances

plt.figure(figsize=(9, 6))
sns.barplot(x=importances.values, y=importances.index, color='#C44E52')
plt.title('FT-Transformer Permutation Feature Importance (drop in ROC-AUC)')
plt.xlabel('AUC Drop When Shuffled')
plt.tight_layout()
plt.savefig('fig_fttransformer_feature_importance.png', dpi=120)
plt.show()

